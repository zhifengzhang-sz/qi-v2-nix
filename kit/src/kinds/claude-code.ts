// Claude Code's files from a spec: .claude/agents/<role>.md, .claude/workflows/<process>.js, and the rules
// (common.ts). The mapping is README.md's table, Claude Code's column.
import type { Can, ModelClass, Process, Role, Spec } from "../spec.ts";
import { brief, frontMatter, type Generated, rulesFiles } from "./common.ts";
import { RUNNER } from "./runner.ts";

export const MODELS: Readonly<Record<ModelClass, string>> = {
  small: "haiku",
  middle: "sonnet",
  strongest: "opus",
  other: "fable",
};

const TOOLS: Readonly<Record<Can, readonly string[]>> = {
  read: ["Read"],
  search: ["Grep", "Glob"],
  edit: ["Edit", "Write"],
  execute: ["Bash"],
  web: ["WebSearch", "WebFetch"],
};

const roleFile = (role: Role, everyRole: string): Generated => ({
  path: `.claude/agents/${role.front.name}.md`,
  text: `${frontMatter([
    ["name", role.front.name],
    ["description", role.front.for],
    ["model", MODELS[role.front.model]],
    ["effort", role.front.effort],
    ["tools", role.front.can.flatMap((c) => TOOLS[c]).join(", ")],
  ])}\n${brief(role, everyRole)}`,
});

// the Workflow tool's script: a literal meta, the process as data, the runner that reads it
const workflowFile = (p: Process): Generated => ({
  path: `.claude/workflows/${p.name}.js`,
  text: `// generated by the kit from agents/stages/${p.name}.json; do not edit: change the source and run make agents
export const meta = ${JSON.stringify(
    {
      name: p.name,
      description: p.for,
      whenToUse: p.when,
      phases: p.stages.map((s) => ({ title: s.title, detail: s.detail })),
    },
    null,
    2,
  )}

const SPEC = ${JSON.stringify(p, null, 2)}
const MODELS = ${JSON.stringify(MODELS)}
${RUNNER}`,
});

export const claudeCode = (spec: Spec): readonly Generated[] => [
  ...rulesFiles(spec),
  ...spec.roles.map((r) => roleFile(r, spec.everyRole)),
  ...spec.processes.map(workflowFile),
];
